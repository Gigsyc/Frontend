type Tone = "navy" | "white" | "amber" | "ink";
const TONE: Record<Tone, string> = { navy: "#001b56", white: "#ffffff", amber: "#ffb703", ink: "#1c1c1c" };

interface IconProps extends React.SVGProps<SVGSVGElement> {
  tone?: Tone;
  size?: number;
}

export function LogoIcon({ tone = "navy", size = 28, className, ...rest }: IconProps) {
  return (
    <svg viewBox={ICON_VIEWBOX} width={size} height={size * (107.62 / 123.23)} aria-hidden="true" className={cn("shrink-0", className)} {...rest}>
      {ICON_PATHS.map((d, i) => <path key={i} d={d} fill={TONE[tone]} />)}
    </svg>
  );
}

interface WordmarkProps extends React.SVGProps<SVGSVGElement> {
  tone?: Tone;
  /** Colour of the "i" (the human figure). Defaults to amber on dark tones, matching the brand book. */
  dotTone?: Tone;
  height?: number;
}

export function LogoWordmark({ tone = "navy", dotTone, height = 22, className, ...rest }: WordmarkProps) {
  const dot = dotTone ?? (tone === "navy" ? "navy" : "amber");
  return (
    <svg viewBox={WORDMARK_VIEWBOX} height={height} width={height * (242.49 / 77.2)} aria-hidden="true" className={cn("shrink-0", className)} {...rest}>
      {WORDMARK_PATHS.map((d, i) => <path key={i} d={d} fill={i === 1 ? TONE[dot] : TONE[tone]} />)}
    </svg>
  );
}

interface LogoProps {
  /** "dark" renders white wordmark + amber icon for navy backgrounds. */
  variant?: "light" | "dark" | "mono";
  size?: "sm" | "md" | "lg";
  className?: string;
  /** Visually hidden label for screen readers. */
  label?: string;
}

const SIZES = { sm: { icon: 22, word: 16, gap: "gap-1.5" }, md: { icon: 28, word: 20, gap: "gap-2" }, lg: { icon: 40, word: 28, gap: "gap-2.5" } };

/** Full lock-up: icon + wordmark. */
export function Logo({ variant = "light", size = "md", className, label = "GigSyc" }: LogoProps) {
  const s = SIZES[size];
  const iconTone: Tone = variant === "light" ? "amber" : variant === "dark" ? "amber" : "navy";
  const wordTone: Tone = variant === "light" ? "navy" : variant === "dark" ? "white" : "navy";
  return (
    <span className={cn("inline-flex items-center", s.gap, className)}>
      <LogoIcon tone={iconTone} size={s.icon} />
      <LogoWordmark tone={wordTone} height={s.word} />
      <span className="sr-only">{label}</span>
    </span>
  );
}
