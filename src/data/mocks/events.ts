const mkTickets = (id: string, seeds: TicketSeed[] = []): TicketTier[] =>
  seeds.map(([name, price, description], i) => ({ id: `${id}_t${i}`, name, price, description }));

export const EVENTS: Event[] = SEEDS.map((s) => ({
  id: s.id,
  slug: s.slug,
  title: s.title,
  tagline: s.tagline,
  description: s.description,
  highlights: s.highlights,
  category: s.category,
  status: s.status ?? "published",
  featured: s.featured ?? false,
  organizerId: s.organizerId,
  place: s.place,
  venue: s.venue,
  address: s.address,
  date: dayOffset(s.d),
  endDate: s.endD !== undefined ? dayOffset(s.endD) : undefined,
  startTime: s.start,
  endTime: s.end,
  doorsOpen: s.doors,
  coverImage: s.img,
  gallery: s.gallery ?? [],
  attendanceMode: s.mode,
  tickets: mkTickets(s.id, s.tickets),
  capacity: s.capacity,
  attending: s.attending,
  ageRestriction: s.age,
  accessibility: ["Step-free access to the main area", "Accessible toilets on site"],
  goodToKnow: s.goodToKnow ?? GENERIC_GOOD_TO_KNOW,
  createdAt: isoOffset(s.submittedD !== undefined ? s.submittedD - 2 : -30, 10),
  submittedAt: s.submittedD !== undefined ? isoOffset(s.submittedD, 11) : undefined,
  reviewedAt: s.reviewedD !== undefined ? isoOffset(s.reviewedD, 9) : undefined,
  reviewNote: s.reviewNote,
  staffedShiftIds: s.staffed ?? [],
}));

export const eventById = (id: string) => EVENTS.find((e) => e.id === id);
export const eventBySlug = (slug: string) => EVENTS.find((e) => e.slug === slug);
